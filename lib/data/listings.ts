function dims(category: Category, base: number): ReviewDimension[] {
  const j = (n: number) => Math.max(3, Math.min(5, base + n));
  const common: ReviewDimension[] = [
    { label: "Communication", value: j(0) },
    { label: "Professionalism", value: j(0.2) },
    { label: "Value", value: j(-0.3) },
  ];
  if (category === "club")
    return [
      ...common,
      { label: "Depth of Playing Schedule", value: j(0.1) },
      { label: "Program Time Allocation", value: j(-0.1) },
    ];
  if (category === "trainer")
    return [
      ...common,
      { label: "Training Tools & Equipment", value: j(0.2) },
      { label: "Facility Quality", value: j(0) },
      { label: "Price vs. Value", value: j(-0.2) },
    ];
  return [...common, { label: "Quality of Alumni", value: j(0.3) }];
}

function makeReviews(category: Category, count: number, avg: number): Review[] {
  const out: Review[] = [];
  const pool = REVIEW_SNIPPETS[category];
  for (let i = 0; i < count; i++) {
    const rating = Math.max(3, Math.min(5, Math.round((avg + (i % 2 === 0 ? 0.2 : -0.2)) * 2) / 2));
    const snip = pool[i % pool.length];
    out.push({
      author: REVIEW_AUTHORS[(i * 3) % REVIEW_AUTHORS.length],
      rating,
      date: `2026-0${(i % 5) + 1}-1${i % 9}`,
      title: snip.title,
      body: snip.body,
      dimensions: dims(category, avg),
      // Most reviewers are confirmed customers; a minority are unverified.
      verified: i % 3 !== 2,
    });
  }
  return out;
}

